import assert from 'node:assert/strict'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.WEIGHT_PREVIEW_URL || 'http://localhost:3000'
const api = process.env.WEIGHT_TEST_API_URL || 'http://localhost:5567'
assert(['localhost', '127.0.0.1'].includes(new URL(api).hostname))
assert.equal(new URL(api).port, '5567', 'browser regression uses a separate synthetic API')
const day = offset => {
  const now = new Date()
  return new Date(now.getTime() - now.getTimezoneOffset() * 60000 + offset * 864e5).toISOString().slice(0, 10)
}
const { token } = await (await fetch(`${api}/__test/token`)).json()
const headers = { authorization: `Bearer ${token}`, 'content-type': 'application/json' }
for (let offset = -4; offset <= 0; offset++) {
  assert.equal((await fetch(`${api}/api/weight/entries/${day(offset)}`, { method: 'PUT', headers, body: JSON.stringify({ weightKg: 80 }) })).status, 200)
}
assert.equal((await fetch(`${api}/api/meals`, { method: 'POST', headers, body: JSON.stringify({ date: day(-50), description: 'Synthetic forgotten breakfast', kcal: 430 }) })).status, 200)
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM } : {}) })
try {
  const page = await browser.newPage({ viewport: { width: 1400, height: 1050 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route(/^http:\/\/(?:localhost|127\.0\.0\.1):(?:5555|5556|5557)\/(?:api|__test)\//, route => {
    const url = new URL(route.request().url())
    return route.continue({ url: `${api}${url.pathname}${url.search}` })
  })
  await page.goto(`${base}/weight`)
  await page.locator('.weight-food').first().waitFor()
  assert.equal(await page.getByRole('button', { name: 'View and edit this day', exact: true }).count(), 0)
  await page.getByRole('button', { name: /^(Set goal|Change goal)$/ }).click({ timeout: 4000 })
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Target weight (kg)').fill('78')
  await dialog.getByLabel('Target date').fill(day(60))
  await dialog.getByRole('button', { name: 'Save goal', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: /^(Estimate daily burn|Edit metabolism and activity)$/ }).click()
  await dialog.getByLabel('Age').fill('35')
  await dialog.getByLabel('Height (cm)').fill('175')
  await dialog.getByLabel('Equation sex').selectOption('male')
  await dialog.getByLabel('Steps per day').fill('6000')
  await dialog.getByRole('combobox', { name: /^Sport/ }).selectOption('strength')
  await dialog.getByLabel('Minutes per session').fill('45')
  await dialog.getByLabel('Sessions per week').fill('3')
  await dialog.getByRole('button', { name: 'Save estimate', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  const plan = page.locator('.weight-goal')
  assert.equal(await page.getByText('KCAL PLAN', { exact: true }).count(), 0)
  await plan.getByRole('button', { name: 'Apply updated plan', exact: true }).click()
  await plan.getByText('Plan is up to date', { exact: true }).waitFor()
  const saved = await (await fetch(`${api}/api/weight`, { headers })).json()
  assert.equal(saved.goals.at(-1).targetWeightKg, 78)
  assert.equal(saved.profile.heightCm, 175)
  assert.equal(saved.profile.stepsPerDay, 6000)
  assert.equal(saved.phases.at(-1).proteinPerKg, 1.5)
  assert.equal(saved.phases.at(-1).startDate, day(0))

  const oldBurn = saved.phases.at(-1).maintenanceKcal
  await page.getByRole('button', { name: 'Edit metabolism and activity', exact: true }).click()
  await dialog.getByLabel('Steps per day').fill('10000')
  await dialog.getByRole('button', { name: 'Save estimate', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert(!(await plan.locator('.weight-energy').getAttribute('aria-label')).includes(`of ${oldBurn} kcal`), 'the unified graphic follows activity edits')
  const unapplied = await (await fetch(`${api}/api/weight`, { headers })).json()
  assert.equal(unapplied.phases.at(-1).maintenanceKcal, oldBurn, 'a preview does not silently accept a phase')
  await page.getByText('HISTORY', { exact: true }).click()
  assert.equal(await page.getByLabel('Open a day').count(), 0)
  assert.equal(await page.getByText('Unreviewed', { exact: true }).count(), 0)
  await page.getByRole('button', { name: `Open ${day(-50)}`, exact: true }).click()
  await dialog.getByText('Synthetic forgotten breakfast', { exact: true }).waitFor()
  assert.equal(await dialog.getByText('Add known calories', { exact: true }).count(), 0)
  assert.equal(await dialog.getByText('Food coverage', { exact: true }).count(), 0)
  await dialog.getByLabel('Weight (kg)').fill('79.5')
  await page.route(`**/api/weight/entries/${day(-50)}`, route => route.fulfill({ status: 500, contentType: 'application/json', body: '{}' }))
  await dialog.getByRole('button', { name: 'Save weight', exact: true }).click()
  await dialog.getByRole('alert').waitFor()
  assert.equal(await dialog.getByLabel('Weight (kg)').inputValue(), '79.5')
  await page.unroute(`**/api/weight/entries/${day(-50)}`)
  await dialog.getByRole('button', { name: 'Save weight', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('dialog button[aria-label="Close day"]')?.disabled)
  await page.mouse.click(20, 200)
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await page.getByRole('button', { name: `Open ${day(-50)}`, exact: true }).evaluate(element => element === document.activeElement), true)
  await page.reload()
  await page.getByText('HISTORY', { exact: true }).click()
  await page.getByRole('button', { name: `Open ${day(-50)}`, exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'the combined plan must fit a phone without horizontal overflow')
  await page.getByRole('button', { name: `Open ${day(-50)}`, exact: true }).click()
  assert((await dialog.boundingBox()).width <= 390)
  const mealCalories = dialog.getByRole('spinbutton', { name: 'kcal for Synthetic forgotten breakfast', exact: true })
  await mealCalories.fill('')
  await dialog.getByRole('heading', { name: day(-50), exact: true }).click()
  await dialog.getByRole('alert').first().waitFor({ timeout: 3000 })
  assert.equal((await (await fetch(`${api}/api/weight/days/${day(-50)}`, { headers })).json()).meals[0].kcal, 430, 'empty calorie input must not overwrite a meal with zero')
  page.once('dialog', prompt => prompt.dismiss())
  await page.keyboard.press('Escape')
  assert(await dialog.isVisible(), 'unfinished calorie correction needs discard confirmation')
  await mealCalories.fill('435')
  const corrected = page.waitForResponse(response => response.url().includes('/api/meals/') && response.request().method() === 'PUT' && response.ok())
  await dialog.getByRole('heading', { name: day(-50), exact: true }).click()
  await corrected
  await page.waitForFunction(() => !document.querySelector('dialog button[aria-label="Close day"]')?.disabled)
  await page.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  const deadlineFixture = await (await fetch(`${api}/api/weight`, { headers })).json()
  deadlineFixture.goals = [{ startDate: day(-10), startWeightKg: 81, targetDate: day(-1), targetWeightKg: 80 }]
  await page.route('**/api/weight', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(deadlineFixture) }))
  await page.reload()
  await page.getByText('Target reached by deadline', { exact: true }).waitFor({ timeout: 3000 })
  const noisyFixture = { ...deadlineFixture, goals: [], entries: Array.from({ length: 8 }, (_, index) => ({ date: day(index - 7), weightKg: 80 + index * 0.3 })), days: Array.from({ length: 7 }, (_, index) => ({ date: day(index - 7), kcal: 100, mealCount: 1 })) }
  await page.route('**/api/weight', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(noisyFixture) }))
  await page.reload()
  await page.locator('.weight-goal .weight-energy').waitFor()
  assert(await page.locator('.weight-goal .weight-energy__marker').evaluate(element => parseFloat(element.style.left) >= 0), 'an implausible early burn estimate must not make the energy graphic negative')
  assert.deepEqual(errors, [])
  console.log('PASS: combined goal/energy plan, steps and sport, explicit acceptance, 1.5 protein, removed controls, historical edits, backdrop, failed drafts, expired goal and mobile drawer')
} finally { await browser.close() }
