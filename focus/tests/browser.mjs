async function context(harness = true) {
  const c = await browser.newContext({ acceptDownloads: true, permissions: ['local-network-access'] })
  contexts.push(c)
  if (api !== 'http://localhost:5556') await c.route('http://localhost:5556/**', route => route.continue({ url: route.request().url().replace('http://localhost:5556', api) }))
  c.on('request', request => requests.push({ phase, method: request.method(), url: request.url(), body: request.postData() ?? '' }))
  await c.route('**/__test/posthog/**', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ config: { enable_collect_everything: true }, featureFlags: {}, sessionRecording: { endpoint: '/s/' }, autocapture_opt_out: false, isAuthenticated: false }) }))
  await c.route('**/*.clerk.accounts.dev/**', route => route.abort())
  if (harness) await c.route(`${base}/finance.html`, route => route.fulfill({ contentType: 'text/html', body: vaultHtml, headers: { 'Cache-Control': 'no-store', 'Referrer-Policy': 'no-referrer' } }))
  c.on('page', page => page.on('pageerror', error => errors.push(error.message)))
  return c
}
