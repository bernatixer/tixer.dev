import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.WEIGHT_PREVIEW_URL || 'http://localhost:3000'
assert(['localhost', '127.0.0.1'].includes(new URL(base).hostname))
const output = process.env.WEIGHT_SCREENSHOT_DIR
assert(output, 'WEIGHT_SCREENSHOT_DIR must point to a private local directory')
await mkdir(output, { recursive: true, mode: 0o700 })
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM } : {}) })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  await page.addInitScript(() => localStorage.setItem('theme', 'cyberDark'))
  const errors = []
  const mutations = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/') && !['GET', 'OPTIONS'].includes(request.method())) mutations.push(request.url()) })
  await page.goto(`${base}/weight`)
  const plan = page.locator('.weight-plan')
  await plan.waitFor()
  const stats = page.locator('.weight-stats')
  assert.equal(await stats.locator('.weight-stat').count(), 4)
  assert.equal(await stats.getByText('To goal', { exact: true }).count(), 0)
  assert.equal(await stats.getByText('Observed daily burn', { exact: true }).count(), 0)
  const bmiTile = stats.locator('.weight-stat').filter({ has: page.getByText('BMI', { exact: true }) })
  console.log(`Current local BMI: ${await bmiTile.locator('strong').innerText()} (${await bmiTile.locator('small').innerText()})`)
  await stats.screenshot({ path: `${output}/final-stats.png` })

  await plan.getByText('AT YOUR RECENT PACE', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Daily calories', exact: true }).click()
  assert((await page.locator('.weight-chart__calories').count()) > 0)
  assert.equal(await page.locator('.weight-lab').count(), 0)
  const foodBox = await page.locator('.weight-overview > .weight-food').boundingBox(), planBox = await plan.boundingBox()
  assert(foodBox.x < planBox.x && Math.abs(foodBox.y - planBox.y) < 2)
  await page.locator('.weight-overview').screenshot({ path: `${output}/final-two-panels.png` })
  await plan.screenshot({ path: `${output}/final-plan.png` })
  await page.screenshot({ path: `${output}/final-desktop.png`, fullPage: true })
  await plan.locator('.weight-plan__past > summary').click()
  await plan.locator('.weight-plan__versions .is-current button').click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Daily intake target (optional)').waitFor()
  await dialog.screenshot({ path: `${output}/final-phase-editor.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  assert(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1))
  await dialog.screenshot({ path: `${output}/final-phase-editor-phone.png` })
  await dialog.getByRole('button', { name: 'Close goal', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Edit metabolism and activity', exact: true }).click()
  if (await dialog.locator('.weight-profile__workout').count() === 0) await dialog.getByRole('button', { name: 'Add workout', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Workout 1 sport', exact: true }).selectOption('running')
  await dialog.getByRole('textbox', { name: 'Workout 1 pace (min/km)', exact: true }).fill('6:00')
  await dialog.getByRole('spinbutton', { name: 'Workout 1 minutes per session', exact: true }).fill('30')
  await dialog.getByRole('spinbutton', { name: 'Workout 1 sessions per week', exact: true }).fill('1')
  console.log(`30-minute local run preview: ${await dialog.locator('.weight-profile__workout-energy').first().innerText()}`)
  await dialog.screenshot({ path: `${output}/final-workouts.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  assert(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1))
  await dialog.screenshot({ path: `${output}/final-workouts-phone.png` })
  page.once('dialog', prompt => prompt.accept())
  await dialog.getByRole('button', { name: 'Close estimate', exact: true }).click()
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await plan.screenshot({ path: `${output}/final-plan-phone.png` })
  await page.screenshot({ path: `${output}/final-phone.png`, fullPage: true })
  assert.deepEqual(errors, [])
  assert.deepEqual(mutations, [], 'preview checks must not save or delete local records')
  console.log('PASS: final local version uses selected real-data copy; desktop/phone and optional-phase editor fit; no record mutations or provider calls')
} finally { await browser.close() }
